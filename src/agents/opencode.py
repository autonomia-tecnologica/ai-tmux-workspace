"""OpenCode adapter for the ACP-shaped agent layer.

The adapter knows only the OpenCode side of one headless run: the profile command, the merged
`OPENCODE_CONFIG` and the json event shape. It carries no Claude flag, no Claude settings and no
capability rule. The conference scope is wired as OpenCode permission rules derived from the same
`conference.STRUCTURAL_FILES` (reads) and `conference.EDITABLE_FILES` (edits) the Claude hook
enforces; the central policy engine stays in
`src/policy.py` and `security/opencode-policy.js`.

The session id is the agent's: the plugin records the real id in `tabs/session-<tab>`, so a tab with
no recorded id opens a fresh session (declared, no `--continue`) instead of adopting the repo's last
session in silence. `prepare` regenerates the plugin copy and the generated config the profile's
server reads, so `workspace restart` brings the current plugin back with the server.
"""
import json
import os
import re
import shlex
from pathlib import Path

import conference
from .base import SESSION_ID_AGENT, Adapter, Update, _t, clip, short_path


def _safe(profile):
    """Profile name as a file name, with the same rule `conference_config` uses."""
    return re.sub(r"[^A-Za-z0-9._-]", "_", str(profile or "opencode")) or "opencode"


def plugin_source():
    """The policy plugin shipped with this checkout (`security/opencode-policy.js`)."""
    import lib

    return Path(lib.BASE) / "security" / "opencode-policy.js"


def plugin_path(profile):
    """Workspace-owned copy of the plugin OpenCode loads for `profile` (regenerated by `prepare`).

    It lives under `$WS_STATE/settings/` so a restart of the profile's server always reads the plugin
    of the running code instead of an old installed copy. The plugin resolves the policy CLI through
    `WS_DIR`, which the server exports, or through its own path."""
    import lib

    return lib.settings_dir() / f"opencode-plugin-{_safe(profile)}.js"


def generated_config_path(profile):
    """Generated OpenCode config of the profile: the declared keys plus the workspace plugin."""
    import lib

    return lib.settings_dir() / f"opencode-{_safe(profile)}.json"


def _write(path, text, mode=0o600):
    """Write `text` to `path` atomically, creating the workspace settings directory when missing."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f"{path.name}.{os.getpid()}.tmp")
    try:
        temporary.write_text(text, encoding="utf-8")
        conference._chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)
    return path


def conference_permissions():
    """OpenCode permission rules: everything denied, then the structural files readable and the
    editable ones writable.

    `README.md` edits ask instead of allowing: a non-interactive run cannot confirm them, so the
    direct write does not happen. The Claude path turns the same intent into a pending diff.
    """
    readme = "README.md"
    rules = [
        {"action": "*", "resource": "*", "effect": "deny"},
        {"action": "external_directory", "resource": "*", "effect": "deny"},
    ]
    rules += [{"action": "read", "resource": name, "effect": "allow"}
              for name in conference.STRUCTURAL_FILES]
    for name in conference.EDITABLE_FILES:
        effect = "ask" if name == readme else "allow"
        rules.append({"action": "edit", "resource": name, "effect": effect})
    return rules


def conference_config(profile):
    """Merged OpenCode config for the run: the profile's config plus the conference permissions."""
    import lib

    settings = {}
    source = lib.profile_config(profile)
    if source:
        try:
            settings = json.loads(Path(source).read_text(encoding="utf-8"))
        except (OSError, ValueError):
            settings = {}
    if not isinstance(settings, dict):
        settings = {}
    settings["permissions"] = conference_permissions()
    folder = conference._ensure_dir(conference.state_dir() / "settings")
    path = folder / f"opencode-conference-{_safe(profile)}.json"
    path.write_text(json.dumps(settings, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
                    encoding="utf-8")
    conference._chmod(path)
    return path


class OpenCodeAdapter(Adapter):
    """OpenCode: profile command + `OPENCODE_CONFIG` + json stream.

    The session id is the agent's: the OpenCode plugin records the real id in
    `tabs/session-<tab>`, so a new tab cannot be told an id at launch. A tab with no recorded id
    therefore opens a fresh session (no `--continue`), and never adopts the repo's last session in
    silence; only the legacy two-argument opening (`continue_args`) continues it."""

    harness = "opencode"
    stream_format = "json"
    session_id_source = SESSION_ID_AGENT

    def prepare(self, profile=None):
        """Regenerate the plugin and the config this profile's server reads, and return the config
        path used at launch.

        The plugin is a byte copy of `security/opencode-policy.js` under `$WS_STATE/settings/`, and
        the generated config is the profile's declared config plus `plugin` pointing at it, as a
        `file://` URL (declared plugins are kept). `workspace restart` calls this, so the restarted
        server loads the plugin of the running code. A declared config that exists but is not plain
        JSON (JSONC, unreadable) is kept as the launch config: the plugin copy is still regenerated,
        but the workspace does not rewrite a file it cannot read safely. When the plugin copy itself
        cannot be written, the declared config is kept so the session still opens."""
        import lib

        profile = self.profile_name(profile)
        source = plugin_source()
        target = plugin_path(profile)
        try:
            _write(target, source.read_text(encoding="utf-8"), 0o644)
        except OSError:
            return lib.profile_config(profile)
        declared = lib.profile_config(profile)
        settings = {}
        if declared:
            try:
                settings = json.loads(Path(declared).read_text(encoding="utf-8"))
            except FileNotFoundError:
                settings = {}
            except (OSError, ValueError):
                return declared
        if not isinstance(settings, dict):
            return declared
        plugins = settings.get("plugin")
        plugins = [str(item) for item in plugins] if isinstance(plugins, list) else []
        url = Path(os.path.abspath(target)).as_uri()
        if url not in plugins:
            plugins.append(url)
        settings["plugin"] = plugins
        return str(_write(generated_config_path(profile),
                          json.dumps(settings, indent=2, ensure_ascii=False, sort_keys=True) + "\n"))

    def launch(self, profile=None, mode=""):
        """Interactive OpenCode command: the profile command under the generated config, with the
        user binary folders on PATH. `mode` is ignored: the permission mode is OpenCode's own."""
        import lib

        profile = self.profile_name(profile)
        command = self.command_line(profile)
        current = os.environ.get("PATH", "")
        path = lib.agent_path(current)
        exports = [f"PATH={shlex.quote(path)}"] if path != current else []
        config = self.prepare(profile)
        if config:
            exports.append(f"OPENCODE_CONFIG={shlex.quote(config)}")
        return f"env {' '.join(exports)} {command}" if exports else command

    def resume_args(self, session):
        """Resume exactly the session id the plugin recorded for the tab."""
        return ["--session", str(session)]

    def fresh_args(self, session=""):
        """Start a new session: declared, no `--continue`.

        The adapter receives no id (`session_id_source` is the agent), and the repo's last session
        is not adopted in silence; the plugin records the new id once the session runs."""
        return []

    def continue_args(self):
        """Continue the repo's last session (legacy opening only; a tab never relies on this)."""
        return ["--continue"]

    def command(self, profile=None):
        """Headless OpenCode run with the profile's config and the conference permissions."""
        profile = self.profile_name(profile)
        command = self.command_line(profile)
        config = conference_config(profile)
        self._settings = str(config)
        return (f"env OPENCODE_CONFIG={shlex.quote(str(config))} {command} "
                f"run --format json --archived")

    def settings_path(self, profile=None):
        if getattr(self, "_settings", ""):
            return self._settings
        return str(conference_config(self.profile_name(profile)))

    def status_label(self, repo, part):
        """Header label for an OpenCode `tool_use` part; "" when the tool is not worth showing."""
        part = part if isinstance(part, dict) else {}
        state = part.get("state") if isinstance(part.get("state"), dict) else {}
        tool_input = state.get("input") if isinstance(state.get("input"), dict) else {}
        tool = str(part.get("tool") or "").lower()
        if tool == "read":
            return _t("conference.status.reading", path=short_path(repo, tool_input.get("path")))
        if tool == "grep":
            return _t("conference.status.searching", pattern=clip(tool_input.get("pattern")))
        if tool == "glob":
            return _t("conference.status.looking", pattern=clip(tool_input.get("pattern")))
        return ""

    def update(self, event, repo=""):
        """One OpenCode json event: a text part or a tool step."""
        kind = event.get("type")
        part = event.get("part") if isinstance(event.get("part"), dict) else {}
        if kind == "text":
            text = part.get("text")
            return Update(text=text) if isinstance(text, str) else Update()
        if kind == "tool_use":
            return Update(status=self.status_label(repo, part), reset=True)
        return Update()
